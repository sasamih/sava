"""Tile-size selection and transform-dialect script generation.

For every linalg.matmul the compiler picks tile sizes (tm, tn, tk) that

  * respect the per-instruction MXU limits (MXU_M/N/K <= max_m/n/k),
  * divide the problem size (v0 has no remainder/padding handling),
  * keep A, B and the f32 accumulator tile within an SRAM budget.

It then emits a transform-dialect script that, per matmul,

  1. tiles the parallel dims (M, N) and fuses the producing linalg.fill,
  2. promotes the accumulator tile to SRAM (memory space 1),
  3. tiles the reduction dim (K),
  4. promotes the A and B tiles to SRAM.

The generated script is written to the dump directory; it can be edited and
passed back with `--transform-script` to experiment with other schedules.
"""

from __future__ import annotations

from dataclasses import dataclass

from iree.compiler import ir

SRAM_SPACE = 1
ELEM_BYTES = {"f32": 4, "bf16": 2, "i32": 4, "i8": 1}
DEFAULT_MATMUL_MAPS = (
    "[affine_map<(d0, d1, d2) -> (d0, d2)>, affine_map<(d0, d1, d2) -> (d2, d1)>, "
    "affine_map<(d0, d1, d2) -> (d0, d1)>]"
)


class TilingError(Exception):
    pass


@dataclass
class MatmulPlan:
    op_id: int
    m: int
    n: int
    k: int
    elem: str
    tiles: tuple[int, int, int]

    def sram_bytes(self) -> int:
        tm, tn, tk = self.tiles
        return (tm * tk + tk * tn) * ELEM_BYTES[self.elem] + tm * tn * 4


def _divisors_desc(n: int, limit: int) -> list[int]:
    return [d for d in range(min(n, limit), 0, -1) if n % d == 0]


def choose_matmul_tiles(m: int, n: int, k: int, elem: str, cfg: dict) -> tuple[int, int, int]:
    mxu = cfg["mxu"]
    # Leave half of SRAM free for future double buffering / fused epilogues.
    budget = cfg["sram"]["bytes"] // 2
    eb = ELEM_BYTES[elem]
    # Prefer large K and N tiles (fewer weight-stationary passes, fewer
    # accumulator round trips), then large M.
    for tk in _divisors_desc(k, mxu["max_k"]):
        for tn in _divisors_desc(n, mxu["max_n"]):
            for tm in _divisors_desc(m, mxu["max_m"]):
                if (tm * tk + tk * tn) * eb + tm * tn * 4 <= budget:
                    return tm, tn, tk
    raise TilingError(f"no tiling of {m}x{n}x{k} fits in SRAM")


def plan_module(module: ir.Module, cfg: dict) -> list[MatmulPlan]:
    """Annotates each linalg.matmul with `sava.op_id` and picks its tiles."""
    plans: list[MatmulPlan] = []

    def visit(op: ir.Operation):
        for region in op.regions:
            for block in region.blocks:
                for child in block.operations:
                    visit(child.operation)
        if op.name != "linalg.matmul":
            return
        if "indexing_maps" in op.attributes and str(op.attributes["indexing_maps"]) != DEFAULT_MATMUL_MAPS:
            raise TilingError(f"transposed/broadcast matmul variants are not supported yet: {op}")
        a, b, c = (ir.RankedTensorType(v.type) for v in op.operands)
        if str(a.element_type) != str(b.element_type) or str(a.element_type) not in ("f32", "bf16") \
                or str(c.element_type) != "f32":
            raise TilingError("matmul must be f32 x f32 -> f32 or bf16 x bf16 -> f32, got "
                              f"{a.element_type} x {b.element_type} -> {c.element_type}")
        producer = op.operands[2].owner  # an op, or a Block for block arguments
        if getattr(getattr(producer, "operation", producer), "name", None) != "linalg.fill":
            raise TilingError("v0 expects the matmul accumulator to be produced by linalg.fill")
        m, k = a.shape
        n = b.shape[1]
        elem = str(a.element_type)
        op_id = len(plans)
        op.attributes["sava.op_id"] = ir.IntegerAttr.get(ir.IntegerType.get_signless(64), op_id)
        plans.append(MatmulPlan(op_id, m, n, k, elem, choose_matmul_tiles(m, n, k, elem, cfg)))

    visit(module.operation)
    if not plans:
        raise TilingError("no linalg.matmul found; v0 only compiles matmul kernels")
    return plans


def make_transform_script(plans: list[MatmulPlan]) -> str:
    any_op = "!transform.any_op"
    lines = [
        "// Generated by sava.compiler.tiling -- edit and pass back with --transform-script.",
        "module attributes {transform.with_named_sequence} {",
        f"  transform.named_sequence @__transform_main(%root: {any_op} {{transform.readonly}}) {{",
    ]
    for p in plans:
        tm, tn, tk = p.tiles
        v = f"%mm{p.op_id}"
        lines += [
            f"    // matmul #{p.op_id}: {p.m}x{p.k} * {p.k}x{p.n} ({p.elem}) -> tiles "
            f"M={tm} N={tn} K={tk}, SRAM {p.sram_bytes()} B",
            f"    {v} = transform.structured.match ops{{[\"linalg.matmul\"]}} "
            f"attributes {{sava.op_id = {p.op_id} : i64}} in %root : ({any_op}) -> {any_op}",
            "    // 1. Tile M and N; fuse the accumulator init (linalg.fill) into the loop nest.",
            f"    {v}_mn, {v}_loop_m, {v}_loop_n = transform.structured.fuse {v} "
            f"tile_sizes [{tm}, {tn}, 0] : ({any_op}) -> ({any_op}, {any_op}, {any_op})",
            "    // 2. The accumulator tile lives in SRAM for the whole K loop.",
            f"    {v}_fill = transform.get_producer_of_operand {v}_mn[2] : ({any_op}) -> {any_op}",
            f"    {v}_acc = transform.get_operand {v}_fill[1] : ({any_op}) -> !transform.any_value",
            f"    transform.structured.promote_tensor to {SRAM_SPACE} {v}_acc : !transform.any_value",
            "    // 3. Tile the reduction dimension K.",
            f"    {v}_mnk, {v}_loop_k = transform.structured.tile_using_for {v}_mn "
            f"tile_sizes [0, 0, {tk}] : ({any_op}) -> ({any_op}, {any_op})",
            "    // 4. Stage the A and B tiles into SRAM (becomes DMA loads).",
            f"    {v}_a = transform.get_operand {v}_mnk[0] : ({any_op}) -> !transform.any_value",
            f"    {v}_b = transform.get_operand {v}_mnk[1] : ({any_op}) -> !transform.any_value",
            f"    transform.structured.promote_tensor to {SRAM_SPACE} {v}_a : !transform.any_value",
            f"    transform.structured.promote_tensor to {SRAM_SPACE} {v}_b : !transform.any_value",
        ]
    lines += [
        f"    %funcs = transform.structured.match ops{{[\"func.func\"]}} in %root : ({any_op}) -> {any_op}",
        "    transform.apply_patterns to %funcs {",
        "      transform.apply_patterns.canonicalization",
        f"    }} : {any_op}",
        "    transform.yield",
        "  }",
        "}",
    ]
    return "\n".join(lines) + "\n"
