#!/usr/bin/env python3
"""Generates the C++ ISA/config header for the simulator from arch/*.json.

The JSON files under arch/ are the single source of truth for the ISA (like a
TableGen file in LLVM). The simulator includes the generated header; the
Python tools read the JSON directly.

Usage: gen_isa_header.py --isa arch/isa.json --config arch/sava-v0.json -o isa_gen.h
"""
import argparse
import json
import re


def ident(mnemonic: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", mnemonic).upper()


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--isa", required=True)
    p.add_argument("--config", required=True)
    p.add_argument("-o", "--output", required=True)
    args = p.parse_args()

    with open(args.isa) as f:
        isa = json.load(f)
    with open(args.config) as f:
        cfg = json.load(f)

    out = []
    w = out.append
    w("// GENERATED by tools/gen_isa_header.py from arch/isa.json and")
    w(f"// arch/{cfg['name']}.json. Do not edit.")
    w("#pragma once")
    w("#include <cstdint>")
    w("")
    w("namespace sava::isa {")
    w("")
    w(f'inline constexpr const char* kIsaVersion = "{isa["version"]}";')
    w("")
    for name, fld in isa["encoding"]["fields"].items():
        w(f"inline constexpr unsigned k{name.capitalize()}Lsb = {fld['lsb']};")
        w(f"inline constexpr unsigned k{name.capitalize()}Bits = {fld['bits']};")
    w("")

    w("enum class Opcode : uint8_t {")
    for ins in isa["instructions"]:
        w(f"  {ident(ins['mnemonic'])} = {ins['opcode']},")
    w("};")
    w("")

    w("enum class Unit : uint8_t { Scalar, Dma, Mxu, Vpu };")
    w("")
    w("enum class OperandKind : uint8_t { None, Reg, Csr, Int, F32, PcRel, Mask };")
    w("enum class Field : uint8_t { None, Rd, Rs1, Rs2, Rs3, Imm };")
    w("")
    w("struct OperandInfo {")
    w("  Field field;")
    w("  OperandKind kind;")
    w("};")
    w("")
    w("struct InstrInfo {")
    w("  const char* mnemonic;")
    w("  Opcode opcode;")
    w("  Unit unit;")
    w("  uint8_t num_operands;")
    w("  OperandInfo operands[4];")
    w("};")
    w("")
    kind_map = {"reg": "Reg", "csr": "Csr", "int": "Int", "f32": "F32", "pcrel": "PcRel", "mask": "Mask"}
    unit_map = {"scalar": "Scalar", "dma": "Dma", "mxu": "Mxu", "vpu": "Vpu"}
    w("inline constexpr InstrInfo kInstrTable[] = {")
    for ins in isa["instructions"]:
        ops = [f"{{Field::{fld.capitalize()}, OperandKind::{kind_map[kind]}}}" for fld, kind in ins["operands"]]
        while len(ops) < 4:
            ops.append("{Field::None, OperandKind::None}")
        w(f'  {{"{ins["mnemonic"]}", Opcode::{ident(ins["mnemonic"])}, Unit::{unit_map[ins["unit"]]}, '
          f'{len(ins["operands"])}, {{{", ".join(ops)}}}}},')
    w("};")
    w("")
    w("inline const InstrInfo* lookup(uint8_t opcode) {")
    w("  for (const auto& info : kInstrTable)")
    w("    if (static_cast<uint8_t>(info.opcode) == opcode) return &info;")
    w("  return nullptr;")
    w("}")
    w("")

    w("enum Csr : uint8_t {")
    for c in isa["csrs"]:
        w(f"  CSR_{c['name']} = {c['id']},")
    w("};")
    w("inline constexpr unsigned kNumCsrs = 32;")
    w("")
    w("inline const char* csrName(unsigned id) {")
    w("  switch (id) {")
    for c in isa["csrs"]:
        w(f'    case {c["id"]}: return "{c["name"]}";')
    w("    default: return nullptr;")
    w("  }")
    w("}")
    w("")
    w("inline bool csrIsReadOnly(unsigned id) {")
    w("  switch (id) {")
    for c in isa["csrs"]:
        if c["access"] == "ro":
            w(f"    case {c['id']}:")
    w("      return true;")
    w("    default: return false;")
    w("  }")
    w("}")
    w("")
    w("}  // namespace sava::isa")
    w("")

    w("namespace sava::defaults {")
    w(f"inline constexpr double kClockGhz = {cfg['clock_ghz']};")
    w(f"inline constexpr uint64_t kDramBytes = {cfg['dram']['bytes']}ull;")
    w(f"inline constexpr uint32_t kDramBytesPerCycle = {cfg['dram']['bandwidth_bytes_per_cycle']};")
    w(f"inline constexpr uint32_t kDramLatency = {cfg['dram']['latency_cycles']};")
    w(f"inline constexpr uint32_t kSramBytes = {cfg['sram']['bytes']};")
    w(f"inline constexpr uint32_t kDmaTags = {cfg['dma']['tags']};")
    w(f"inline constexpr uint32_t kDmaQueueDepth = {cfg['dma']['queue_depth']};")
    w(f"inline constexpr uint32_t kMxuArrayDim = {cfg['mxu']['array_dim']};")
    w(f"inline constexpr uint32_t kMxuMaxM = {cfg['mxu']['max_m']};")
    w(f"inline constexpr uint32_t kMxuMaxN = {cfg['mxu']['max_n']};")
    w(f"inline constexpr uint32_t kMxuMaxK = {cfg['mxu']['max_k']};")
    w(f"inline constexpr uint32_t kMxuF32Slowdown = {cfg['mxu']['f32_slowdown']};")
    w(f"inline constexpr uint32_t kMxuQueueDepth = {cfg['mxu']['queue_depth']};")
    w(f"inline constexpr uint32_t kVpuLanes = {cfg['vpu']['lanes']};")
    w(f"inline constexpr uint32_t kVpuLatency = {cfg['vpu']['latency_cycles']};")
    w(f"inline constexpr uint32_t kVpuTranscendentalSlowdown = {cfg['vpu']['transcendental_slowdown']};")
    w(f"inline constexpr uint32_t kVpuQueueDepth = {cfg['vpu']['queue_depth']};")
    w(f"inline constexpr uint32_t kCoresPerChip = {cfg['cores_per_chip']};")
    w("}  // namespace sava::defaults")

    with open(args.output, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
